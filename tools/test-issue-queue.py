#!/usr/bin/env python3
"""The issue queue's three decisions: which issues a body waits on, whether a comment is an
agent's, and whether a claim is past its lease. Usage: tools/test-issue-queue.py"""
import datetime
import importlib.util
from pathlib import Path

spec = importlib.util.spec_from_file_location("queue", Path(__file__).with_name("issue-queue.py"))
queue = importlib.util.module_from_spec(spec)
spec.loader.exec_module(queue)

body = "Fix it.\n\nBlocked by #12\n- blocked by #7\nSee #99 and the text blocked by #5 mid-line.\n"
assert queue.blockers(body) == {12, 7}, queue.blockers(body)
assert queue.from_agent("Claim: studio, 2026-11-11T10:00Z")
assert queue.from_agent("Done.\n\n_Generated by [Claude Code](https://claude.ai/code)_")
assert queue.from_agent("anything", "Bot")
assert not queue.from_agent("Use the theme background. Result: looks fine to me")
now = datetime.datetime(2026, 11, 11, 12, 0, tzinfo=datetime.timezone.utc)
assert queue.expired(now, ["2026-11-11T07:59:00Z"])
assert not queue.expired(now, ["2026-11-11T07:59:00Z", "2026-11-11T08:01:00Z"])
print("PASS blockers {7, 12}; agent and human comments told apart; a 4 h lease expires at 4 h 1 min")
